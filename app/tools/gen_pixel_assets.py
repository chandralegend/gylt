#!/usr/bin/env python3
"""Generate GYLT/DesignSystem/Generated/PixelData.swift.

Sources (single source of truth):
  - Pixel grids for the coach and wordmark: ../GYLT/03-Design/Logo-Kit/source/build_logo_kit.py
  - Sneaker grid: tools/sprites/sneaker.txt
  - Icons: tools/icons/*.svg (pixelarticons 1.8.1, MIT; see tools/icons/LICENSE)

    python3 tools/gen_pixel_assets.py
"""
import ast, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
KIT = os.path.join(ROOT, "..", "GYLT", "03-Design", "Logo-Kit", "source", "build_logo_kit.py")
OUT = os.path.join(ROOT, "GYLT", "DesignSystem", "Generated", "PixelData.swift")


def literal(tree, name):
    for n in tree.body:
        if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == name:
            # grids use plain string arithmetic ("B" + "l"*19); evaluated with builtins disabled
            return eval(compile(ast.Expression(n.value), KIT, "eval"), {"__builtins__": {}}, {})
    raise KeyError(name)


kit = ast.parse(open(KIT).read())
CAP, GRUMPY, PLEASED, SMALL, LETTERS = (literal(kit, n) for n in ("CAP", "GRUMPY", "PLEASED", "SMALL", "LETTERS"))


def coach(face):
    return CAP + [".#" + r + "#." for r in face] + [".." + "#" * 20 + ".."]


word = ["", "", "", "", "", "", "", "", ""]
for i, ch in enumerate("GYLT"):
    for y in range(9):
        word[y] += (".." if i else "") + LETTERS[ch][y]
sneaker = open(os.path.join(HERE, "sprites", "sneaker.txt")).read().split()

COACH_PAL = {"#": 0x1C1B18, "W": 0xECEBE6, "h": 0xFFFFFF, "g": 0x8F8E86, "d": 0x64635C, "b": 0xFF6548,
             "B": 0xC23F20, "l": 0xFF8A70, "H": 0xFFE6DE, "e": 0xF5F4F0}
SNEAKER_PAL = {"#": 0x1C1B18, "w": 0xF5F4F0, "c": 0xC23F20, "g": 0xD9D6CC, "r": 0xFF8A70}
WORD_PAL = {"#": 0x1C1B18}


def swift_rows(rows):
    return "[\n" + "".join(f'        "{r}",\n' for r in rows) + "    ]"


def swift_pal(p):
    return "[" + ", ".join(f'"{k}": 0x{v:06X}' for k, v in p.items()) + "]"


# ---- icons: SVG path -> polygons (rectilinear: M m H h V v L l Z z)
def parse_path(d):
    toks = re.findall(r"[MmLlHhVvZz]|-?\d*\.?\d+", d)
    polys, cur, i = [], [], 0
    x = y = sx = sy = 0.0
    cmd = None
    def num():
        nonlocal i
        v = float(toks[i]); i += 1; return v
    while i < len(toks):
        if re.match(r"[A-Za-z]", toks[i]):
            cmd = toks[i]; i += 1
            if cmd in "Zz":
                if cur: polys.append(cur)
                cur = []; x, y = sx, sy
                continue
        if cmd in "Mm":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if cmd == "m" else (nx, ny)
            if cur: polys.append(cur)
            cur = [x, y]; sx, sy = x, y
            cmd = "l" if cmd == "m" else "L"
        elif cmd in "Ll":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if cmd == "l" else (nx, ny)
            cur += [x, y]
        elif cmd in "Hh":
            nx = num(); x = x + nx if cmd == "h" else nx; cur += [x, y]
        elif cmd in "Vv":
            ny = num(); y = y + ny if cmd == "v" else ny; cur += [x, y]
        else:
            raise ValueError(f"unsupported command {cmd}")
    if cur: polys.append(cur)
    return polys


def fmt(v):
    return str(int(v)) if float(v).is_integer() else str(v)


icons = {}
for f in sorted(os.listdir(os.path.join(HERE, "icons"))):
    if f.endswith(".svg"):
        ds = re.findall(r'\bd="([^"]+)"', open(os.path.join(HERE, "icons", f)).read())
        icons[f[:-4]] = [p for d in ds for p in parse_path(d)]


def camel(name):
    parts = name.split("-")
    out = parts[0] + "".join(p.capitalize() for p in parts[1:])
    return out if not out[0].isdigit() else "n" + out


cases = "\n".join(f'    case {camel(n)} = "{n}"' for n in icons)
paths = "\n".join(
    f'        case .{camel(n)}: return [' + ", ".join("[" + ", ".join(fmt(v) for v in p) + "]" for p in polys) + "]"
    for n, polys in icons.items()
)

src = f'''// GENERATED by tools/gen_pixel_assets.py. Do not edit by hand.
// Icons: pixelarticons 1.8.1 by Gerrit Halfmann (MIT), see tools/icons/LICENSE.
import CoreGraphics

struct PixelSpriteData {{
    let rows: [String]
    let palette: [Character: UInt32]
    var width: Int {{ rows.first?.count ?? 0 }}
    var height: Int {{ rows.count }}
}}

enum PixelData {{
    static let coach = PixelSpriteData(rows: {swift_rows(coach(GRUMPY))}, palette: {swift_pal(COACH_PAL)})
    static let coachPleased = PixelSpriteData(rows: {swift_rows(coach(PLEASED))}, palette: {swift_pal(COACH_PAL)})
    static let coachSmall = PixelSpriteData(rows: {swift_rows(SMALL)}, palette: {swift_pal(COACH_PAL)})
    static let sneaker = PixelSpriteData(rows: {swift_rows(sneaker)}, palette: {swift_pal(SNEAKER_PAL)})
    /// Single colour: the "#" cells take the tint passed at draw time.
    static let wordmark = PixelSpriteData(rows: {swift_rows(word)}, palette: {swift_pal(WORD_PAL)})
}}

/// 24 × 24 pixel icons. Each icon is a list of closed polygons filled with the even-odd rule.
enum PxIcon: String, CaseIterable {{
{cases}

    var polygons: [[CGFloat]] {{
        switch self {{
{paths}
        }}
    }}
}}
'''
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write(src)
print("wrote", OUT, f"({len(icons)} icons, coach {len(coach(GRUMPY)[0])}x{len(coach(GRUMPY))}, wordmark {len(word[0])}x9)")
